-- Разове виправлення даних: оплати за вересень 2026 помилково завели в липень.
--
-- Схему не чіпає — переносить `billing_month`, і тільки його. `paid_at` лишається
-- як є: у жодну суму він не входить, лише підписує рядок в історії дитини.
-- Ідентифікатори теж лишаються, тож прикріплені квитанції (`payment_receipts`
-- посилаються на `payment_id`) переїжджають разом з оплатами й не гинуть — на
-- відміну від «видалити й завести заново», де каскад стер би їх безповоротно.
--
-- Виконується один раз: drizzle позначить міграцію застосованою, а на порожній
-- базі перша ж перевірка виходить без змін.
DO $$
DECLARE
  moved integer;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM "payments" WHERE "billing_month" = DATE '2026-07-01'
  ) THEN
    RAISE NOTICE '0026: оплат за липень 2026 немає — переносити нічого';
    RETURN;
  END IF;

  -- Знімок «як було» — щоб відкотити навіть після того, як транзакція
  -- міграції закриється. Таблиця тимчасова за призначенням, не за типом:
  -- `TEMP` зникла б разом зі з'єднанням, а вона потрібна саме після.
  CREATE TABLE IF NOT EXISTS "payments_backup_20260906" AS
    SELECT * FROM "payments" WHERE "billing_month" = DATE '2026-07-01';

  UPDATE "payments"
     SET "billing_month" = DATE '2026-09-01'
   WHERE "billing_month" = DATE '2026-07-01';
  GET DIAGNOSTICS moved = ROW_COUNT;

  -- Закритий місяць віддається із замороженого знімка, а не перераховується
  -- (lib/month-close.ts). Якби липень чи вересень встигли закрити до цього
  -- деплою, сторінки й далі показували б перенесені оплати на старому місці —
  -- тобто в двох місяцях одночасно. Знімок, знятий до виправлення, більше не
  -- відповідає даним, тож його прибираємо: місяць знову рахується наживо й
  -- може бути закритий заново вже з правильними числами.
  DELETE FROM "month_closes"
   WHERE "month" IN (DATE '2026-07-01', DATE '2026-09-01');

  RAISE NOTICE '0026: перенесено % оплат із 2026-07 у 2026-09', moved;
END $$;
