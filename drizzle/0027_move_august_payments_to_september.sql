-- Разове виправлення даних: оплати за вересень 2026 завели в серпень.
--
-- Попередня спроба (0026) називала липень — місяць був вказаний помилково, і на
-- проді вона нічого не знайшла та вийшла без змін.
--
-- Переноситься тільки `billing_month`. `paid_at` лишається як є (у суми він не
-- входить, лише підписує рядок в історії дитини), ідентифікатори теж — тож
-- прикріплені квитанції їдуть разом з оплатами замість того, щоб згинути в
-- каскаді, як сталося б при «видалити й завести заново».
DO $$
DECLARE
  branch_count integer;
  moved integer;
BEGIN
  -- Спершу — чи є що переносити. На порожній базі міграція має пройти без шуму,
  -- інакше розгортання з нуля впало б назавжди.
  IF NOT EXISTS (
    SELECT 1 FROM "payments" WHERE "billing_month" = DATE '2026-08-01'
  ) THEN
    RAISE NOTICE '0027: оплат за серпень 2026 немає — переносити нічого';
    RETURN;
  END IF;

  -- Оплата належить філії через дитину, і філія тут рівно одна — тому перенос
  -- іде за самим лише місяцем, без звуження. Якщо філій виявиться більше,
  -- припущення хибне: у решти серпень міг бути справжнім, і забрати його разом
  -- з помилковим не можна. Тоді краще зупинити розгортання, ніж мовчки
  -- перекинути чужі гроші на інший місяць.
  SELECT count(*) INTO branch_count FROM "branches";
  IF branch_count > 1 THEN
    RAISE EXCEPTION
      '0027: у базі % філій, а перенос розрахований на одну — звузьте міграцію до потрібної',
      branch_count;
  END IF;

  -- Знімок «як було» — щоб відкотити вже після того, як транзакція міграції
  -- закриється. Заразом це і єдиний надійний доказ, що міграція відпрацювала:
  -- `RAISE NOTICE` у логах Railway не видно, а таблиця або є, або її немає.
  CREATE TABLE IF NOT EXISTS "payments_backup_aug_to_sep_2026" AS
    SELECT * FROM "payments" WHERE "billing_month" = DATE '2026-08-01';

  UPDATE "payments"
     SET "billing_month" = DATE '2026-09-01'
   WHERE "billing_month" = DATE '2026-08-01';
  GET DIAGNOSTICS moved = ROW_COUNT;

  -- Закритий місяць віддається із замороженого знімка, а не перераховується
  -- (lib/month-close.ts). Якби серпень чи вересень встигли закрити до цього
  -- розгортання, сторінки й далі показували б перенесені оплати на старому
  -- місці — тобто в двох місяцях одночасно. Знімок, знятий до виправлення,
  -- даним більше не відповідає, тож його прибираємо: місяць знову рахується
  -- наживо й може бути закритий заново вже з правильними числами.
  DELETE FROM "month_closes"
   WHERE "month" IN (DATE '2026-08-01', DATE '2026-09-01');

  RAISE NOTICE '0027: перенесено % оплат із 2026-08 у 2026-09', moved;
END $$;
